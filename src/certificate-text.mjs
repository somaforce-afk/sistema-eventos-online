import {PDFDocument,StandardFonts,decodePDFRawStream,rgb} from './pdf-lib-vendor.mjs';

const styleVersion='eventos:name-uppercase-bold:v1';
export function certificateTextRuns(body,values){
  const runs=[];let offset=0;
  for(const match of body.matchAll(/{{\s*([^{}]+)\s*}}/g)){
    runs.push({text:body.slice(offset,match.index),bold:false});
    const key=match[1].trim(),value=String(values[key]??'');
    runs.push({text:key==='nome'?value.toLocaleUpperCase('pt-BR'):value,bold:key==='nome'});
    offset=match.index+match[0].length;
  }
  runs.push({text:body.slice(offset),bold:false});
  return runs.map(run=>({...run,text:run.text.replace(/[\u0000-\u0009\u000b-\u001f\u007f]/g,' ')}));
}
function layout(runs,font,boldFont,size,width){
  const lines=[[]];let used=0,pendingSpace=false;
  function append(text,bold){const line=lines.at(-1),last=line.at(-1);if(last?.bold===bold)last.text+=text;else line.push({text,bold});used+=(bold?boldFont:font).widthOfTextAtSize(text,size);}
  function newline(){lines.push([]);used=0;pendingSpace=false;}
  for(const run of runs)for(const token of run.text.split(/(\n|[^\S\n]+)/).filter(Boolean)){
    if(token==='\n'){newline();continue;}
    if(/^\s+$/.test(token)){pendingSpace=true;continue;}
    const face=run.bold?boldFont:font,space=pendingSpace&&used?font.widthOfTextAtSize(' ',size):0;
    if(used&&used+space+face.widthOfTextAtSize(token,size)>width)newline();
    if(pendingSpace&&used)append(' ',false);
    pendingSpace=false;
    for(const char of token){if(used&&used+face.widthOfTextAtSize(char,size)>width)newline();append(char,run.bold);}
  }
  return lines;
}
export async function drawCertificateText(document,page,config,values){
  const serif=config.font==='TimesRoman';
  const font=await document.embedFont(serif?StandardFonts.TimesRoman:StandardFonts.Helvetica);
  const boldFont=await document.embedFont(serif?StandardFonts.TimesRomanBold:StandardFonts.HelveticaBold);
  const runs=config.text_runs||certificateTextRuns(config.body,values);
  try{for(const run of runs)(run.bold?boldFont:font).encodeText(run.text.replaceAll('\n',' '));}catch{throw new Error('O texto contém caractere que a fonte selecionada não suporta. Revise os campos do certificado.');}
  const {width,height}=page.getSize(),area={x:width*config.x/100,y:height*config.y/100,width:width*config.width/100,height:height*config.height/100};
  let size=Number(config.font_size),lines;
  for(;size>=8;size-=0.5){lines=layout(runs,font,boldFont,size,area.width);if(lines.length*size*1.3<=area.height)break;}
  if(size<8)throw new Error('O texto não cabe na área configurada. Aumente a área ou reduza o texto do modelo.');
  const hex=config.color.slice(1),color=rgb(parseInt(hex.slice(0,2),16)/255,parseInt(hex.slice(2,4),16)/255,parseInt(hex.slice(4,6),16)/255);
  for(const [index,line]of lines.entries()){
    const measured=line.reduce((sum,run)=>sum+(run.bold?boldFont:font).widthOfTextAtSize(run.text,size),0);
    let x=area.x+(config.align==='center'?(area.width-measured)/2:config.align==='right'?area.width-measured:0);
    for(const run of line){const face=run.bold?boldFont:font;page.drawText(run.text,{x,y:height-area.y-size-index*size*1.3,size,font:face,color});x+=face.widthOfTextAtSize(run.text,size);}
  }
  document.setSubject(styleVersion);
  document.setKeywords(['eventos-render:'+encodeURIComponent(JSON.stringify(Object.fromEntries(['x','y','width','height','font_size','font','align','color'].map(key=>[key,config[key]]))))]);
  return font;
}

const extraWinAnsi=[0x20ac,0x81,0x201a,0x192,0x201e,0x2026,0x2020,0x2021,0x2c6,0x2030,0x160,0x2039,0x152,0x8d,0x17d,0x8f,0x90,0x2018,0x2019,0x201c,0x201d,0x2022,0x2013,0x2014,0x2dc,0x2122,0x161,0x203a,0x153,0x9d,0x17e,0x178];
function decodeText(hex){return hex.match(/../g).map(pair=>{const byte=parseInt(pair,16);return String.fromCodePoint(byte>=128&&byte<160?extraWinAnsi[byte-128]:byte);}).join('');}

// Upgrade only text streams generated by this app. Background, footer and issued data stay intact.
export async function restyleIssuedCertificate(bytes,name){
  const document=await PDFDocument.load(bytes);
  if(document.getSubject()===styleVersion)return null;
  if(document.getPageCount()!==1)throw new Error('Certificado emitido com formato inesperado.');
  const page=document.getPage(0),contents=page.node.Contents(),streams=[],blocks=[];
  for(let index=0;index<contents.size();index++){
    const source=new TextDecoder().decode(decodePDFRawStream(document.context.lookup(contents.get(index))).decode());
    const cleaned=source.replace(/q\s+BT\s+([\s\S]*?)ET\s+Q/g,(block,operators)=>{
      const face=operators.match(/\/(Helvetica|Times-Roman)-\d+\s+([\d.]+)\s+Tf/),position=operators.match(/1 0 0 1 ([\d.-]+) ([\d.-]+) Tm/),text=operators.match(/<([0-9a-f]+)> Tj/i),color=operators.match(/([\d.]+) ([\d.]+) ([\d.]+) rg/);
      if(!face||!position||!text||!color||Number(face[2])<8||Number(position[2])<20)return block;
      blocks.push({font:face[1],size:Number(face[2]),x:Number(position[1]),y:Number(position[2]),text:decodeText(text[1]),color:color.slice(1).map(Number)});return '';
    });
    streams.push(cleaned);
  }
  if(!blocks.length)throw new Error('Não foi possível localizar o texto original do certificado.');
  const escaped=name.trim().split(/\s+/).map(word=>word.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('\\s+');
  const original=blocks.map(block=>block.text).join('\n'),pattern=new RegExp(escaped,'u');
  if(!pattern.test(original))throw new Error('O nome não corresponde ao certificado emitido.');
  const font=await document.embedFont(blocks[0].font==='Times-Roman'?StandardFonts.TimesRoman:StandardFonts.Helvetica);
  const left=Math.min(...blocks.map(block=>block.x)),right=Math.max(...blocks.map(block=>block.x+font.widthOfTextAtSize(block.text,block.size))),first=blocks[0],{width,height}=page.getSize();
  const centers=blocks.map(block=>block.x+font.widthOfTextAtSize(block.text,block.size)/2);
  const centered=Math.max(...centers)-Math.min(...centers)<1;
  const oldHeight=first.y-Math.min(...blocks.map(block=>block.y))+first.size*1.3;
  const config={body:original.replace(pattern,'{{nome}}'),font:first.font==='Times-Roman'?'TimesRoman':'Helvetica',font_size:first.size,x:left/width*100,y:(height-first.y-first.size)/height*100,width:(right-left+0.1)/width*100,height:oldHeight/height*100,align:centered?'center':'left',color:'#'+first.color.map(channel=>Math.round(channel*255).toString(16).padStart(2,'0')).join('')};
  for(let index=0;index<streams.length;index++)contents.set(index,document.context.register(document.context.flateStream(streams[index])));
  await drawCertificateText(document,page,config,{nome:name});
  return document.save();
}

export async function reviseIssuedCertificate(bytes,before,after){
  const document=await PDFDocument.load(bytes);
  if(document.getPageCount()!==1)throw new Error('O certificado existente tem formato inesperado. Nenhum dado foi alterado.');
  const page=document.getPage(0),contents=page.node.Contents(),streams=[],blocks=[];
  for(let index=0;index<contents.size();index++){
    const source=new TextDecoder().decode(decodePDFRawStream(document.context.lookup(contents.get(index))).decode());
    streams.push(source.replace(/q\s+BT\s+([\s\S]*?)ET\s+Q/g,(block,operators)=>{
      const face=operators.match(/\/(Helvetica(?:-Bold)?|Times-Roman|Times-Bold)-\d+\s+([\d.]+)\s+Tf/),position=operators.match(/1 0 0 1 ([\d.-]+) ([\d.-]+) Tm/),text=operators.match(/<([0-9a-f]+)> Tj/i),color=operators.match(/([\d.]+) ([\d.]+) ([\d.]+) rg/);
      if(!face||!position||!text||!color||Number(face[2])<8||Number(position[2])<20)return block;
      blocks.push({font:face[1],size:Number(face[2]),x:Number(position[1]),y:Number(position[2]),text:decodeText(text[1]),color:color.slice(1).map(Number)});return '';
    }));
  }
  if(!blocks.length)throw new Error('Não foi possível localizar o texto do certificado. Nenhum dado foi alterado.');
  blocks.sort((a,b)=>Math.abs(a.y-b.y)>.1?b.y-a.y:a.x-b.x);
  const lines=[];
  for(const block of blocks){let line=lines.at(-1);if(!line||Math.abs(line.y-block.y)>.1){line={y:block.y,blocks:[]};lines.push(line);}line.blocks.push(block);}
  const escaped=value=>value.trim().split(/\s+/).map(word=>word.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('\\s+');
  let body=lines.map(line=>line.blocks.map(block=>block.text).join('')).join('\n');
  const pattern=new RegExp(escaped(before.name),'iu');
  if(!pattern.test(body))throw new Error('O nome não corresponde ao certificado existente. Nenhum dado foi alterado.');
  const marker='__NAME_'+crypto.randomUUID()+'__';
  body=body.replace(pattern,()=>marker);
  const faces={};for(const key of new Set(blocks.map(block=>block.font)))faces[key]=await document.embedFont(key.startsWith('Times')?(key==='Times-Bold'?StandardFonts.TimesRomanBold:StandardFonts.TimesRoman):(key==='Helvetica-Bold'?StandardFonts.HelveticaBold:StandardFonts.Helvetica));
  const edges=lines.map(line=>({left:Math.min(...line.blocks.map(block=>block.x)),right:Math.max(...line.blocks.map(block=>block.x+faces[block.font].widthOfTextAtSize(block.text,block.size)))}));
  const left=Math.min(...edges.map(edge=>edge.left)),right=Math.max(...edges.map(edge=>edge.right)),centers=edges.map(edge=>(edge.left+edge.right)/2),first=blocks[0],{width,height}=page.getSize();
  const align=Math.max(...centers)-Math.min(...centers)<1?'center':Math.max(...edges.map(edge=>edge.right))-Math.min(...edges.map(edge=>edge.right))<1?'right':'left';
  const saved=document.getKeywords()?.match(/eventos-render:([^\s]+)/)?.[1];
  const text_runs=body.split(marker).flatMap((text,index)=>index?[{text:after.name.toLocaleUpperCase('pt-BR'),bold:true},{text,bold:false}]:[{text,bold:false}]);
  const config={body,font:first.font.startsWith('Times')?'TimesRoman':'Helvetica',font_size:first.size,x:left/width*100,y:(height-first.y-first.size)/height*100,width:(right-left+.1)/width*100,height:(first.y-Math.min(...blocks.map(block=>block.y))+first.size*1.3)/height*100,align,color:'#'+first.color.map(channel=>Math.round(channel*255).toString(16).padStart(2,'0')).join(''),...(saved?JSON.parse(decodeURIComponent(saved)):{}),text_runs};
  for(let index=0;index<streams.length;index++)contents.set(index,document.context.register(document.context.flateStream(streams[index])));
  await drawCertificateText(document,page,config,{nome:after.name});document.setTitle('Certificado - '+after.name);
  return document.save();
}
